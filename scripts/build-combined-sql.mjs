#!/usr/bin/env node
/**
 * Concatenates supabase/01..08 into a single file that can be pasted into the
 * Supabase SQL Editor in one go. Keeps the numbered files as the source of
 * truth so the two can never drift.
 *
 *   npm run db:bundle
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'supabase')
const files = readdirSync(dir).filter((f) => /^\d\d_.*\.sql$/.test(f)).sort()

const header = `-- ============================================================================
--  myRPS — COMPLETE DATABASE SETUP
--
--  HOW TO USE THIS FILE
--
--  1. Open your project at https://supabase.com/dashboard
--  2. Click "SQL Editor" in the left sidebar
--  3. Click "New query"
--  4. Copy EVERYTHING in this file and paste it in
--  5. Click "Run"  (or press Ctrl+Enter)
--
--  It takes a few seconds. When it finishes you should see
--  "Success. No rows returned" — that is what success looks like.
--
--  Running it a second time is harmless. It will not delete student data.
--
--  Generated from the files in supabase/. Do not edit this file by hand —
--  edit the numbered file and run "npm run db:bundle".
-- ============================================================================

`

const body = files
  .map((f) => `\n-- ===== ${f} ${'='.repeat(Math.max(0, 62 - f.length))}\n\n${readFileSync(join(dir, f), 'utf8').trim()}\n`)
  .join('\n')

const footer = `

-- ============================================================================
--  Did it work? Run this afterwards in a new query. Every row should say OK.
-- ============================================================================
-- select 'tables created' as check,
--        case when count(*) >= 15 then 'OK' else 'PROBLEM' end as result
--   from pg_tables where schemaname = 'public'
-- union all
-- select 'security rules on',
--        case when count(*) = 0 then 'OK' else 'PROBLEM' end
--   from pg_class c join pg_namespace n on n.oid = c.relnamespace
--  where n.nspname = 'public' and c.relkind = 'r' and not c.relrowsecurity
-- union all
-- select 'curriculum loaded',
--        case when count(*) = 108 then 'OK' else 'PROBLEM' end
--   from public.curriculum_subjects
-- union all
-- select 'psychometric questions',
--        case when count(*) = 70 then 'OK' else 'PROBLEM' end
--   from public.psychometric_items;
`

writeFileSync(join(root, 'RUN_THIS_IN_SUPABASE.sql'), header + body + footer)
console.log(`Bundled ${files.length} files -> RUN_THIS_IN_SUPABASE.sql`)
